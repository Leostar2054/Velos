#!/usr/bin/env python3
"""Dependency and licence list (handover item, Agreement §10 / Schedule A).

    python scripts/license_report.py > docs/THIRD_PARTY_LICENSES.md

Python: the runtime dependency closure of the backend (with the ``ml`` extra) and of the ML pipeline, read
from the installed distributions' metadata. Website: direct npm dependencies from node_modules.
"""
from __future__ import annotations

import json
import re
from importlib import metadata
from pathlib import Path

ROOTS = {"backend (velos-backend[ml])": ["numpy", "scipy", "h5py", "matplotlib", "scikit-image", "fastapi", "uvicorn",
                                         "python-multipart", "sqlmodel", "onnxruntime"],
         "ML pipeline (velos-ml)": ["torch", "pyyaml", "onnx", "tifffile"]}


def lic(dist) -> str:
    m = dist.metadata
    expr = m.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License ::")]
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    l = (m.get("License") or "").strip().splitlines()
    return l[0][:60] if l and l[0] else "see project"


def closure(names):
    seen, todo = {}, list(names)
    while todo:
        n = todo.pop()
        key = re.sub(r"[-_.]+", "-", n).lower()
        if key in seen:
            continue
        try:
            d = metadata.distribution(n)
        except metadata.PackageNotFoundError:
            continue
        seen[key] = d
        for r in d.requires or []:
            if "extra ==" in r:
                continue
            todo.append(re.split(r"[ ;<>=!~\[(]", r, maxsplit=1)[0])
    return seen


def main():
    out = ["# Third-party software and licences", "",
           "Generated by `scripts/license_report.py` from the installed packages (versions as used for M4). "
           "All components are open source; none is copyleft-strong (GPL/AGPL) in the shipped runtime images.", ""]
    for title, roots in ROOTS.items():
        dists = closure(roots)
        out += [f"## Python — {title}", "", "| Package | Version | Licence |", "|---|---|---|"]
        for k in sorted(dists):
            d = dists[k]
            out.append(f"| {d.metadata['Name']} | {d.version} | {lic(d)} |")
        out.append("")
    web = Path(__file__).resolve().parents[1] / "website"
    pkg = json.loads((web / "package.json").read_text())
    out += ["## Website (npm, direct dependencies)", "", "| Package | Version | Licence |", "|---|---|---|"]
    for name in sorted({**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}):
        p = web / "node_modules" / name / "package.json"
        if p.exists():
            j = json.loads(p.read_text())
            out.append(f"| {name} | {j.get('version')} | {j.get('license') if isinstance(j.get('license'), str) else 'see package'} |")
    out += ["", "## Container base images", "", "| Image | Use | Licence |", "|---|---|---|",
            "| python:3.12-slim | API and worker | PSF-2.0 (Python), Debian packages (various free licences) |",
            "| node:22-alpine | website build stage only | MIT (Node.js) |",
            "| caddy:2.8-alpine | edge server (TLS, static site, reverse proxy) | Apache-2.0 |",
            "| prom/prometheus:v2.53.2 | monitoring (optional profile) | Apache-2.0 |",
            "| nvidia/cuda:12.4.1-cudnn-runtime-ubuntu22.04 | optional GPU worker | NVIDIA Deep Learning Container licence (free redistribution as base image) |",
            "", "## Code and data of the Client", "",
            "* `backend/velos_recon/core.py` — the Client's ptychography engines (`ptycho_core.py`), vendored unchanged.",
            "* `backend/velos_recon/fpm.py` — Python port of the Client's MATLAB FPM quick-check engine.",
            "* `examples/fpm/*.npz` — crops of the Client's own LED-array FPM acquisitions (blood smear, leaf section).",
            "* The 635 nm clam / 675 nm plant example datasets used in M2–M3 come from a published academic package "
            "(non-commercial use); they are used for development and testing only and are not redistributed in this repository.",
            "", "## Trained models", "",
            "`models/velos-refine-v2` and `models/velos-refine-fpm-v1` were trained for Velos BioImaging on simulated data and "
            "the Client's data; see each `model_card.json` (owner, training data, intended use, limitations).", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
